def 取自身目录():
    """拿到 exe（或未打包时的 py 脚本）所在目录"""
    if getattr(sys, "frozen", False):
        return os.path.dirname(os.path.abspath(sys.executable))
    return os.path.dirname(os.path.abspath(sys.argv[0]))


日志路径 = ""      # 运行时确定


def 写日志(内容):
    """所有关键步骤都记到这里 —— exe 没有控制台，日志是唯一的排查手段"""
    global 日志路径
    if not 日志路径:
        return
    # 太长就先清掉，防止日志无限膨胀
    if os.path.exists(日志路径) and os.path.getsize(日志路径) > 日志上限:
        with open(日志路径, "w", encoding="utf-8-sig") as f:
            f.write("")
    with open(日志路径, "a", encoding="utf-8-sig") as f:
        f.write("[%s] %s\n" % (time.strftime("%Y-%m-%d %H:%M:%S"), 内容))


def 找播放器目录(自身目录):
    """先看 exe 同目录是不是就有一整套播放器文件（便携用法），否则用写死目录"""
    if os.path.exists(os.path.join(自身目录, "冰冰播放器.html")):
        return 自身目录
    if os.path.exists(os.path.join(写死目录, "冰冰播放器.html")):
        return 写死目录
    return ""


def 转本地地址(路径):
    """转成 file:/// 直链。用标准库生成，中文、空格、# 都会被正确转义"""
    from pathlib import Path
    return Path(路径).as_uri()


def 清空清单(播放器目录):
    """
    把 _播放列表.js 覆盖成一份空清单。

    【为什么要这么做】播放器启动时会读磁盘上这份清单文件。如果里面还残留着
    上次扫描的结果，播放器一打开就会冒出上次那个目录的视频列表 ——
    这正是五阿哥要消掉的「历史记录」。所以每次「没指定视频文件」地启动时，
    都把它覆盖成空的。

    【为什么是覆盖而不是删除】删除会撞上安全删除钩子（本机实测被拦过），
    而写一个小文件是纯写入操作，安全且效果等价。

    返回写进去的内容，方便调用方记日志。
    """
    路径 = os.path.join(播放器目录, "_播放列表.js")

    # stamp 不能省：播放器只认「新鲜」的清单，空清单也得带着刚打的时间戳，
    # 否则会被它当成过期数据丢掉 —— 最终效果一样，但日志里就看不出发生了什么
    时刻 = int(time.time() * 1000)
    内容 = ('window.BB_PLAYLIST={"dir":"","play":"","stamp":%d,"files":[]};' % 时刻)

    # 跟 _扫描.ps1 保持一致的 UTF-8 + BOM 写法
    with open(路径, "w", encoding="utf-8-sig") as f:
        f.write(内容)

    写日志("已把播放列表清空：%s" % 路径)
    return 内容


