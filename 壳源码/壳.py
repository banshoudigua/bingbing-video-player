# 供「干跑」判断用的小开关（列表是为了能在函数里改到它）
干跑标志 = [False]


def 主流程():
    global 日志路径

    自身目录 = 取自身目录()
    日志路径 = os.path.join(自身目录, 日志名)

    参数列表 = sys.argv[1:]
    写日志("=" * 60)
    写日志("被唤起。参数 %d 个：%s" % (len(参数列表), 参数列表))

    # 把「开关」和「文件路径」分开。
    # 不能只取 0 号参数 —— Windows 调起来时参数顺序不保证，
    # 而且我们自己也可能传 --dry 之类的开关在前面（实测踩过这个坑）
    开关列表 = [a for a in 参数列表 if a.startswith("--")]
    路径列表 = [a for a in 参数列表 if not a.startswith("--")]

    干跑 = ("--dry" in 开关列表) or (os.environ.get("BBPLAYER_DRY") == "1")
    干跑标志[0] = 干跑
    if 干跑:
        写日志("处于 dry 模式：只记录将要执行的命令，不真正启动浏览器")

    # ---- 0. 先看是不是「关联管理」类开关 ----
    #   这几个开关不是拿来放视频的，处理完就直接退出，别去启动浏览器
    for 开关, 模式名 in (("--设为默认", "设为默认"),
                       ("--恢复默认", "恢复默认"),
                       ("--查状态", "查状态")):
        if 开关 in 开关列表:
            写日志("识别到关联开关：%s" % 开关)
            目录 = 找播放器目录(自身目录) or 写死目录
            return 执行关联操作(模式名, 目录)

    # ---- 1. 定位播放器目录 ----
    播放器目录 = 找播放器目录(自身目录)
    if not 播放器目录:
        写日志("错误：找不到 冰冰播放器.html，自身目录=%s，写死目录=%s" % (自身目录, 写死目录))
        提示("找不到播放器主程序，请检查目录是否被移动。")
        return 1
    写日志("播放器目录：%s" % 播放器目录)

    # ---- 2. 决定扫描目标 ----
    #   有文件参数（双击视频 / 右键打开 / 多选）→ 扫「第一个真实存在」的那一个
    #   没有任何有效参数（双击 exe 本身）        → 不扫，改为清空列表（见第 3 步）
    扫描目标 = ""
    for 候选 in 路径列表:
        if os.path.exists(候选):
            扫描目标 = 候选
            写日志("扫描目标：%s" % 候选)
            if len(路径列表) > 1:
                写日志("提示：本次共传入 %d 个路径，只按第一个来定位片库" % len(路径列表))
            break
        写日志("忽略：参数指向的路径不存在 → %s" % 候选)

    # ---- 3. 生成 _播放列表.js ----
    #   【不留痕 · 关键】没有视频文件参数时（双击 exe 图标打开播放器），
    #   不再去扫播放器目录，而是直接写一份空清单盖掉上次那份。
    #   以前是「扫播放器自己所在目录」，于是每次打开都会带出上次那个目录的列表，
    #   看起来就是「历史记录」；现在直接给一份空的，干干净净。
    if not 扫描目标:
        写日志("无有效文件参数：清空播放列表，让播放器以空状态打开")
        清空清单(播放器目录)
    else:
        扫描脚本 = os.path.join(播放器目录, "_扫描.ps1")
        if os.path.exists(扫描脚本):
            命令 = [
                "powershell", "-NoProfile", "-ExecutionPolicy", "Bypass",
                "-File", 扫描脚本,
                "-PlayerDir", 播放器目录,
                "-Target", 扫描目标,
            ]
            写日志("执行扫描：%s" % " ".join(命令))
            结果 = subprocess.run(命令, creationflags=不显窗口,
                                  capture_output=True)
            输出 = 结果.stdout.decode("gbk", "replace").strip()
            写日志("扫描退出码 %d，输出：%s" % (结果.returncode, 输出.replace("\r\n", " | ")))
        else:
            写日志("警告：没有 _扫描.ps1，跳过扫描（播放列表会由拖入决定）")

    # ---- 3.5 起本地小桥 ----
    #   页面上的「打开文件夹 / 删除文件 / 文件信息」都要碰磁盘，网页自己做不到，
    #   必须由外壳代劳 —— 这就是小桥存在的理由（原理与安全边界见 小桥.py 顶部）。
    #
    #   没有扫描目标时不起桥：那时列表本来就是空的，没有东西可操作，别白开一个进程。
    桥端口 = 0
    桥口令 = ""
    小桥 = None
    if 扫描目标:
        # 允许操作的根目录 = 本次扫描的那个目录
        #（扫描目标是文件时，扫的是它所在的文件夹）
        允许目录 = 扫描目标 if os.path.isdir(扫描目标) else os.path.dirname(扫描目标)
        小桥 = 载入小桥()
        桥端口, 桥口令 = 小桥.启动(允许目录, 写日志)

        # 【2026-10-13 补】干跑也真起一次桥，随即收摊。
        #
        # 为什么非要在干跑里起：小桥是延迟 import 的模块。干跑如果完全不碰它，
        # 「它到底有没有被打进 exe」这件事就永远验不出来 —— 漏了要等用户真去点
        # 「删除」才发现。起一次能同时证明三件事：模块在包里、端口真绑得上、
        # 地址片段拼得对。起完立刻停，不留监听、不留进程，也不碰浏览器和注册表。
        if 干跑:
            if 桥端口:
                写日志("[干跑] 小桥试绑成功：端口 %d，口令 %d 位十六进制"
                       % (桥端口, len(桥口令)))
            else:
                写日志("[干跑] 小桥没起来 —— 见上面那行写的原因")

    # ---- 4. 找浏览器 ----
    浏览器 = ""
    for 候选 in 浏览器候选:
        if 候选 and os.path.exists(候选):
            浏览器 = 候选
            break
    if not 浏览器:
        写日志("没找到 Chrome / Edge，交给系统默认浏览器")
        提示("没有找到 Chrome 或 Edge，将用系统默认浏览器打开。")
        os.startfile(os.path.join(播放器目录, "冰冰播放器.html"))
        return 0
    写日志("浏览器：%s" % 浏览器)

    # ---- 5. 打开播放器 ----
    地址 = 转本地地址(os.path.join(播放器目录, "冰冰播放器.html"))

    # 把小桥的端口与口令挂在地址的 #bbp= 片段上捎给页面。
    # 为什么走碎片而不是写进 _播放列表.js：清单管「放什么」，小桥管「怎么跟外壳说话」，
    # 两件事分开更干净，也不动清单本身的格式。
    if 桥端口:
        地址 = 地址 + "#bbp=" + str(桥端口) + "-" + 桥口令

    完整命令 = [浏览器, "--app=" + 地址] + 浏览器参数尾巴

    # 【口令不写进日志】日志是磁盘上的明文文件，口令写进去就等于把
    # 「谁能操作这个目录」印在了明处。要确认片段拼上了，看到端口就够，口令打码。
    # （验收脚本要拿口令时，是从 Chrome 的启动命令行里读的 —— 那同时也证明了
    #   片段真的交到浏览器手上了，比看日志更有说服力。）
    打码地址 = 地址.replace(桥口令, "…") if 桥口令 else 地址

    if 干跑:
        写日志("[干跑] 本该启动：%s --app=%s" % (浏览器, 打码地址))
        if 桥端口:
            写日志("[干跑] 地址里已带上小桥片段：#bbp=%d-…" % 桥端口)
            if 小桥 and 小桥.停止():
                写日志("[干跑] 小桥已收摊（干跑不留监听、不留进程）")
        else:
            写日志("[干跑] 没有小桥可收（本次没起桥）")
        写日志("（dry 模式，不真正启动浏览器）")
        return 0

    写日志("启动：%s --app=%s" % (浏览器, 打码地址))
    subprocess.Popen(完整命令, close_fds=True)
    写日志("已发出启动指令")

    # ---- 6. 守着小桥，直到页面关闭 ----
    #   这一步会让本进程一直挂着（约 15MB），换来的是页面上「删除 / 打开文件夹」能用。
    #   页面每 15 秒 ping 一次；窗口一关心跳就停，小桥在这里自动收摊，
    #   所以不会留一个后台进程在跑（和「关掉重开不留痕迹」的口径一致）。
    if 桥端口:
        退出原因 = 小桥.等待页面结束(写日志)
        写日志("小桥退出：%s" % 退出原因)

    return 0


def 提示(内容):
    """出错时给个能看见的提示。exe 没有控制台，只能弹原生消息框"""
    报结果("冰冰播放器", 内容, 0x30)


if __name__ == "__main__":
    sys.exit(主流程())
