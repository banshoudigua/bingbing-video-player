def 报结果(标题, 正文, 图标=0x40):
    """
    弹一个原生消息框。exe 没有控制台，结果只能靠弹窗告诉用户。
    图标：0x40 = 信息，0x30 = 警告，0x10 = 错误
    """
    框 = ctypes.WinDLL("user32", use_last_error=True)
    框.MessageBoxW.argtypes = [ctypes.c_void_p, ctypes.c_wchar_p,
                              ctypes.c_wchar_p, ctypes.c_uint]
    框.MessageBoxW.restype = ctypes.c_int
    框.MessageBoxW(None, 正文, 标题, 图标)


