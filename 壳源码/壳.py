"""
冰冰播放器 · 外壳程序（打包成 exe 用）

它的职责非常单一：
    被 Windows 用「打开方式」唤起 → 拿到视频文件路径 → 叫 _扫描.ps1 生成播放列表
    → 用系统已装的 Chrome / Edge 以「应用模式」打开 冰冰播放器.html

真正的播放逻辑全在 冰冰播放器.html 里，本程序只是个「传递路径」的壳。

后来多担了一件事：页面上要能「打开所在文件夹 / 删除文件 / 查看文件信息」，
而网页自己碰不了磁盘（浏览器安全限制，绕不过去），所以外壳在播放期间还会起一个
只监听 127.0.0.1 的小服务来代劳（见 小桥.py），窗口一关它自动收摊退出。

为什么要做成 exe：
    Windows 的「打开方式」只认可执行文件（exe），脚本 / 快捷方式都不能直接登记。

【编码与坑】
    · 本脚本存 UTF-8 即可，Python 3 默认按 UTF-8 读源码
    · powershell 子进程必须加 CREATE_NO_WINDOW，否则会闪一个黑窗口
    · 打包用 PyInstaller --onefile --noconsole，这样双击不弹控制台
    · 因为 --noconsole 看不到任何输出，所有关键步骤都写进 冰冰播放器壳.log，
      出问题直接看那个日志
"""

